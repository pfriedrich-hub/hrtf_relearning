    import time
    import sounddevice

    SAMPLERATE = 48000     # must match the audio interface's rate
    DEVICE = None          # None = system default; else index/name from the list printed below
    LEVEL = 70             # dB (slab units, uncalibrated) — set a comfortable level on the first sound
    print(sounddevice.query_devices())
    sounddevice.default.device = DEVICE
    slab.set_default_samplerate(SAMPLERATE)

    gb = GenericBinaural(samplerate=SAMPLERATE)                                     # DT990 EQ + colouring + reverb
    gb_dry = GenericBinaural(samplerate=SAMPLERATE, reverb=False)                   # no reverb
    gb_raw = GenericBinaural(samplerate=SAMPLERATE, reverb=False,
                             hrtf_colouring=False, headphones=None)                 # sphere only

    def burst_train(n=3, burst=0.1, gap=0.05):
        """Pink-noise burst train, fresh noise every call, 5 ms ramps."""
        parts = []
        for _ in range(n):
            b = slab.Sound.pinknoise(duration=burst, samplerate=SAMPLERATE).ramp(duration=0.005)
            parts += [b, slab.Sound.silence(duration=gap, samplerate=SAMPLERATE)]
        s = slab.Sound.sequence(*parts)
        s.level = LEVEL
        return s

