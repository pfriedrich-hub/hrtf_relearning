SPEED_OF_SOUND = 343.0


class GenericBinaural:
    """Static generic binaural renderer. Build once, call :meth:`render` per trial.

    Arguments:
        samplerate (int | None): output samplerate; None = slab's default samplerate.
        head_radius (float): sphere radius in metres.
        distance (float): source distance in metres (> head_radius).
        ear_angle (float): ear position in deg from the front (90 = on the interaural
            axis). 100 follows Brown & Duda (1998): ears slightly behind the centre,
            which removes the sphere's contralateral bright spot at 90 deg so the
            ILD grows monotonically up to the side.
        n_taps (int): length of the direct-sound filter.
        hrtf_colouring (bool): impose the mean frontal HRTF colouring.
        headphones (str | Path | None): headphone equalization.
            "DT990"  -- built in: inverse mean DT990 HpTF (24 listeners, symmetric).
            None     -- no equalization.
            Path     -- your own calibration, applied per ear, any samplerate:
                        * .npz with "filter" (2, n_samples) + "samplerate": an inverse
                          FIR, e.g. calibrate_headphones' <ID>/<HP>_equalization.npz
                        * .npz with "frequencies" + "gain_db" ((n,) or (2, n)): the
                          equalization gain in dB (what to APPLY, not the HpTF)
                        * .wav: 2-channel inverse FIR
        reverb (bool): add the diffuse reverb tail.
        t60 (float): reverberation time in seconds (high band decays at
            `t60_high_ratio` * t60 above 4 kHz).
        drr_db (float): direct-to-reverberant energy ratio in dB, for a source at 0 deg.
        predelay (float): gap between direct sound and the start of the tail, s.
        seed (int): seed of the reverb noise.
    """

    def __init__(self, samplerate=None, head_radius=0.0725, distance=1.5, ear_angle=100.0, n_taps=1024,
                 hrtf_colouring=True, headphones="DT990", reverb=True, t60=0.3, drr_db=6.0,
                 predelay=0.004, t60_high_ratio=0.6, seed=0):
        self.samplerate = int(samplerate or slab.get_default_samplerate())
        if distance <= head_radius:
            raise ValueError("distance must be larger than head_radius")
        self.head_radius = float(head_radius)
        self.distance = float(distance)
        self.ear_angle = numpy.deg2rad(float(ear_angle))
        self.n_taps = int(n_taps)
        self.bulk_delay = int(round(0.002 * self.samplerate))  # room for the leading (ipsilateral) ear
        self.reverb, self.t60, self.drr_db = bool(reverb), float(t60), float(drr_db)
        self.predelay, self.t60_high_ratio, self.seed = float(predelay), float(t60_high_ratio), int(seed)
        self._fft_freqs = numpy.fft.rfftfreq(2 * self.n_taps, 1 / self.samplerate)

        # static filter per ear = HRTF colouring + headphone equalization (dB), one min-phase FIR
        grid = 2.0 ** numpy.arange(numpy.log2(20.0), numpy.log2(self.samplerate / 2), 1 / 96)
        gain = numpy.zeros((2, grid.size))
        if hrtf_colouring:
            gain += _on_grid(grid, _TABLE[:, 0], _TABLE[:, 1])
        if isinstance(headphones, str) and headphones.upper() == "DT990":
            gain += _on_grid(grid, _TABLE[:, 0], _TABLE[:, 2])
        elif headphones is not None:
            gain += _on_grid(grid, *_load_equalization(Path(headphones)))
        self.static_ir = numpy.stack([_minimum_phase_ir(grid, g, self.samplerate, self.n_taps)
                                      for g in gain], axis=1)                  # (n_taps, 2)
        # level: slab's pink noise straight ahead keeps its level (power mean over the
        # ears, one factor for both, so a calibration's interaural balance is kept)
        rng_state = numpy.random.get_state()                   # fixed noise -> same gain every
        numpy.random.seed(0)                                   # instance; caller's RNG untouched
        pink = slab.Sound.pinknoise(duration=4.0, samplerate=self.samplerate).data[:, 0]
        numpy.random.set_state(rng_state)
        p_out = numpy.mean([numpy.mean(numpy.convolve(pink, self.static_ir[:, c])[self.n_taps:len(pink)] ** 2)
                            for c in range(2)])
        self.static_ir *= numpy.sqrt(numpy.mean(pink[self.n_taps:] ** 2) / p_out)
        self._static_spec = numpy.fft.rfft(self.static_ir, 2 * self.n_taps, axis=0)  # (n_f, 2)
        self._p_front = self._pressure(self.ear_angle)           # source at 0 deg seen from either ear
        self.tail = self._make_tail() if self.reverb else None

    # ------------------------------------------------------------------ public
    def render(self, sound, azimuth):
        """Return `sound` (mono slab.Sound) as a slab.Binaural at `azimuth` deg
        (negative = left, 0 = front). Output is longer than the input by the
        filter length (direct filter, or reverb tail if enabled)."""
        if sound.samplerate != self.samplerate:
            raise ValueError(f"sound samplerate {sound.samplerate} != renderer samplerate {self.samplerate}")
        if sound.n_channels != 1:
            sound = sound.channel(0)
        out = slab.Binaural(self.filter(azimuth).apply(sound))
        peak = float(numpy.abs(out.data).max())
        if peak > 1.0:
            warnings.warn(f"rendered sound clips (peak {peak:.2f}) — lower the input level by "
                          f"{20 * numpy.log10(peak):.1f} dB or more", stacklevel=2)
        return out

    def filter(self, azimuth):
        """Binaural impulse response at `azimuth` as a 2-channel slab.Filter (fir='IR')."""
        return slab.Filter(data=self._brir(round(float(azimuth), 1)), samplerate=self.samplerate, fir="IR")

    def precompute(self, azimuths):
        """Compute and cache the filters for these azimuths (call before the trial loop)."""
        for az in azimuths:
            self._brir(round(float(az), 1))

    def itd(self, azimuth, band=(200.0, 1500.0)):
        """Interaural delay (s) of the rendered direct sound, from the phase slope in
        `band`; positive = right ear lags (source on the left)."""
        ir = self._direct_ir(round(float(azimuth), 1))
        f = numpy.fft.rfftfreq(8 * self.n_taps, 1 / self.samplerate)
        H = numpy.fft.rfft(ir, 8 * self.n_taps, axis=0)
        phase = numpy.unwrap(numpy.angle(H[:, 1] / H[:, 0]))
        m = (f >= band[0]) & (f <= band[1])
        return -numpy.polyfit(2 * numpy.pi * f[m], phase[m], 1)[0]

    # ---------------------------------------------------------------- internals
    @lru_cache(maxsize=None)
    def _direct_ir(self, azimuth):
        # slab: negative = left. Sphere (math convention): left ear at +90 deg.
        phi = numpy.deg2rad(-azimuth)
        theta_left = numpy.arccos(numpy.clip(numpy.cos(phi - self.ear_angle), -1, 1))
        theta_right = numpy.arccos(numpy.clip(numpy.cos(phi + self.ear_angle), -1, 1))
        n_fft = 2 * self.n_taps
        shift = numpy.exp(-2j * numpy.pi * self._fft_freqs * self.bulk_delay / self.samplerate)
        out = numpy.empty((self.n_taps, 2))
        for ch, theta in enumerate((theta_left, theta_right)):
            rel = self._pressure(theta) / self._p_front
            rel[-1] = numpy.abs(rel[-1])                         # real Nyquist bin
            ir = numpy.fft.irfft(self._static_spec[:, ch] * rel * shift, n_fft)[:self.n_taps]
            out[:, ch] = ir * _fade_out(self.n_taps, self.n_taps // 16)
        return out

    @lru_cache(maxsize=None)
    def _brir(self, azimuth):
        direct = self._direct_ir(azimuth)
        if self.tail is None:
            return direct
        out = self.tail.copy()
        out[:direct.shape[0]] += direct
        return out

    def _pressure(self, theta):
        """Duda & Martens (1998) sphere pressure re. free field at the centre, on the
        renderer's FFT grid, for great-circle angle `theta` between source and ear."""
        f = self._fft_freqs.copy()
        f[0] = min(SPEED_OF_SOUND / (200 * self.head_radius), f[1])  # 0 Hz not computable
        return _sphere_pressure(theta, f, self.head_radius, self.distance)

    def _make_tail(self):
        fs = self.samplerate
        rng = numpy.random.default_rng(self.seed)
        n = int(round(1.2 * self.t60 * fs))
        freqs = numpy.fft.rfftfreq(n, 1 / fs)
        X1, X2 = (numpy.fft.rfft(rng.standard_normal(n)) for _ in range(2))
        # diffuse-field coherence between the ears: sin(kd)/(kd), d = 2 * head radius
        coh = numpy.sinc(2 * freqs * (2 * self.head_radius) / SPEED_OF_SOUND)
        a, b = numpy.sqrt((1 + coh) / 2), numpy.sqrt((1 - coh) / 2)
        spectra = (a * X1 + b * X2, a * X1 - b * X2)
        # two decay bands with a raised-cosine crossover around 4 kHz
        hi = numpy.clip((numpy.log2(numpy.maximum(freqs, 1) / 2830) / 1.0), 0, 1)
        hi = 0.5 - 0.5 * numpy.cos(numpy.pi * hi)
        t = numpy.arange(n) / fs
        env_lo = 10 ** (-3 * t / self.t60)
        env_hi = 10 ** (-3 * t / (self.t60 * self.t60_high_ratio))
        tail = numpy.stack([numpy.fft.irfft(S * (1 - hi), n) * env_lo + numpy.fft.irfft(S * hi, n) * env_hi
                            for S in spectra], axis=1)
        n_in = int(round(0.002 * fs))
        tail[:n_in] *= numpy.sin(numpy.linspace(0, numpy.pi / 2, n_in))[:, None] ** 2
        tail = numpy.stack([numpy.convolve(tail[:, c], self.static_ir[:, c])[:n] for c in range(2)], axis=1)
        # place after the direct sound and scale to the requested DRR (energy at 0 deg)
        start = self.bulk_delay + int(round(self.predelay * fs))
        out = numpy.zeros((start + n, 2))
        out[start:] = tail
        e_direct = numpy.sum(self._direct_ir(0.0) ** 2)
        out *= numpy.sqrt(e_direct / numpy.sum(out ** 2) * 10 ** (-self.drr_db / 10))
        return out


# ---------------------------------------------------------------------- helpers
def _sphere_pressure(theta, frequencies, radius, distance, n_max=100):
    """Rigid-sphere surface pressure for a point source at `distance`, referenced to
    the free-field pressure at the sphere centre (Duda & Martens 1998, Eq. A10).
    Returned with the numpy/pyfar FFT sign convention (conjugate of the paper's)."""
    mu = 2 * numpy.pi * numpy.asarray(frequencies, float) * radius / SPEED_OF_SOUND
    rho = distance / radius
    x = numpy.cos(theta)
    zr, za = 1 / (1j * mu * rho), 1 / (1j * mu)
    Qr2, Qr1 = zr, zr * (1 - zr)
    Qa2, Qa1 = za, za * (1 - za)
    P2, P1 = 1.0, x
    total = zr / (za * (za - 1)) + (3 * x * zr * (zr - 1)) / (za * (2 * za ** 2 - 2 * za + 1))
    with numpy.errstate(over="ignore", invalid="ignore"):
        for m in range(2, n_max + 1):
            P = ((2 * m - 1) * x * P1 - (m - 1) * P2) / m
            Qr = -(2 * m - 1) * zr * Qr1 + Qr2
            Qa = -(2 * m - 1) * za * Qa1 + Qa2
            term = ((2 * m + 1) * P * Qr) / ((m + 1) * za * Qa - Qa1)
            ok = numpy.isfinite(term)
            total[ok] += term[ok]
            Qr2, Qr1, Qa2, Qa1, P2, P1 = Qr1, Qr, Qa1, Qa, P1, P
    # same distance for source and reference -> the propagation terms reduce to exp(-j mu)
    return numpy.conj(rho * numpy.exp(-1j * mu) * total / (1j * mu))


def _on_grid(grid, freqs, gain_db):
    """Interpolate gain_db ((n,) or (2, n), dB) on a log-frequency axis onto `grid`,
    holding the end values; returns (2, len(grid))."""
    gain_db = numpy.atleast_2d(numpy.asarray(gain_db, float))
    keep = numpy.asarray(freqs) > 0
    out = numpy.array([numpy.interp(numpy.log(grid), numpy.log(numpy.asarray(freqs)[keep]), g[keep])
                       for g in gain_db])
    return numpy.repeat(out, 2, axis=0) if out.shape[0] == 1 else out


def _load_equalization(path):
    """(frequencies, gain_db (2, n)) of a headphone equalization file — see `headphones`."""
    if path.suffix.lower() == ".wav":
        snd = slab.Sound(path)
        fir, fs = snd.data.T, snd.samplerate
    else:
        d = numpy.load(path)
        if "gain_db" in d:
            return d["frequencies"], d["gain_db"]
        fir, fs = numpy.atleast_2d(d["filter"]), int(d["samplerate"])
        if fir.shape[0] > fir.shape[1]:                        # (n_samples, 2) -> (2, n_samples)
            fir = fir.T
    if fir.shape[0] != 2:
        raise ValueError(f"{path.name}: expected a 2-channel filter, got shape {fir.shape}")
    n_fft = max(16384, fir.shape[1])
    H = numpy.abs(numpy.fft.rfft(fir, n_fft, axis=1))
    return numpy.fft.rfftfreq(n_fft, 1 / fs), 20 * numpy.log10(numpy.maximum(H, 1e-12))


def _minimum_phase_ir(freqs, gain_db, samplerate, n_taps, n_fft=16384):
    """Minimum-phase FIR from a magnitude response in dB (held constant outside `freqs`)."""
    f = numpy.fft.rfftfreq(n_fft, 1 / samplerate)
    g = numpy.interp(numpy.log(numpy.maximum(f, freqs[0])), numpy.log(freqs), gain_db)
    cep = numpy.fft.irfft(g * numpy.log(10) / 20, n_fft)
    fold = numpy.zeros(n_fft)
    fold[0] = cep[0]
    fold[1:n_fft // 2] = 2 * cep[1:n_fft // 2]
    fold[n_fft // 2] = cep[n_fft // 2]
    ir = numpy.fft.irfft(numpy.exp(numpy.fft.rfft(fold)), n_fft)[:n_taps]
    return ir * _fade_out(n_taps, n_taps // 8)


def _fade_out(n, n_fade):
    w = numpy.ones(n)
    w[n - n_fade:] = numpy.cos(numpy.linspace(0, numpy.pi / 2, n_fade)) ** 2
    return w


