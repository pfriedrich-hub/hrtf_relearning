"""
generic_binaural — static, non-individual binaural rendering on the horizontal
plane for Beyerdynamic DT 990 headphones. numpy + slab only, no head tracking.

Quick test: run the DEMO cells at the bottom of this file (no import needed).
In your own experiment:

    import slab
    from generic_binaural import GenericBinaural

    gb = GenericBinaural(samplerate=48828)        # build once, before the trial loop
    gb.precompute(range(-90, 91, 15))             # optional: warm the filter cache

    noise = slab.Sound.pinknoise(duration=0.3, samplerate=48828)
    noise.level = 70
    stim = gb.render(noise, azimuth=-30)          # slab.Binaural; negative = LEFT (slab convention)
    stim.play()

Signal chain for a source at azimuth `az` (same for every listener):

    sound -> HRTF colouring           mean frontal HRTF of 24 measured listeners,
                                      1/3-octave, identical for both ears
          -> headphone equalization   default: inverse of the mean DT990 HpTF of
                                      the same 24 listeners (symmetric); or your
                                      own calibration file (per ear); or none
                                      (both combined into one minimum-phase FIR)
          -> spherical head           Duda & Martens (1998) rigid sphere, as a
                                      transfer function RELATIVE to 0 deg:
                                      frequency-dependent ITD and head shadow,
                                      exactly 0 ITD / 0 ILD straight ahead,
                                      ears at +-100 deg (Brown & Duda 1998)
          (+ reverb tail)             optional static diffuse tail with the
                                      interaural coherence of a diffuse field,
                                      mixed at a fixed direct-to-reverberant ratio

What it is and is not
---------------------
* Headphone equalization defaults to DT 990s (`headphones="DT990"`). For other
  headphones pass a calibration file, `headphones=Path(".../X_equalization.npz")`
  (see `headphones` below). It must be measured at the BLOCKED EAR-CANAL ENTRANCE,
  the point the HRTF colouring refers to; an eardrum/coupler measurement
  double-counts the ear-canal resonance (~2-4 kHz).
* The colouring is direction-independent: no pinna cues, so no elevation and no
  front/back information. Use for |azimuth| <= 90.
* Distance is fixed (`distance`, default 1.5 m); the sphere's near-field ILD only
  matters below ~1 m. Ears sit at +-100 deg (Brown & Duda 1998), so front and
  back are no longer exactly mirror images, but the difference is a small level
  cue, not a usable front/back cue.
* Level: a pink noise straight ahead keeps its level (direct sound, per ear).
  Lateral sources get the head-shadow level change on each ear. Reverb adds
  10*log10(1 + 10**(-drr_db/10)) dB on top (~1 dB at the default 6 dB DRR).
* The reverb tail is a single static stochastic tail shared by all azimuths
  (seeded, so identical across sessions), passed through the same static filter.

Data: the HRTF colouring and the DT990 equalization are embedded in this file
(table at the top), so the file runs on its own. build_generic_filter.py regenerates it from the cohort. Head radius 0.0725 m matches the low-frequency (phase) ITD of real
heads with this model; 0.0875 is the onset-ITD convention and gives larger ITDs.
"""
